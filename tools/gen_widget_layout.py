"""Generates res/layout/widget_root.xml and widget/Slots.kt from the LiveFont enum.
Run from the repo root: python3 tools/gen_widget_layout.py"""
import re

src = open("app/src/main/java/com/smrh/zujaj/render/RenderCtx.kt").read()
fonts = []  # (ENUM, res, slots)
for m in re.finditer(r'^\s{4}([A-Z_]+)\(F\.\w+, "(\w+)", "[^"]*", \d(?P<rest>[^)]*)\)[,;]', src, re.M):
    rest = m.group("rest")
    sm = re.search(r"slots = (\d+)", rest)
    fonts.append((m.group(1), m.group(2), int(sm.group(1)) if sm else 2))
assert len(fonts) > 10, fonts

FL = 'android:layout_width="match_parent" android:layout_height="match_parent"'
out = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- Generated by tools/gen_widget_layout.py; do not edit by hand. -->',
       f'<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"\n    android:id="@+id/root" {FL}>',
       f'    <ImageView android:id="@+id/bg" {FL}\n        android:scaleType="fitXY" android:contentDescription="@null" />',
       f'    <FrameLayout android:id="@+id/an_wrap" {FL} android:visibility="gone">',
       f'        <AnalogClock android:id="@+id/an_clock" {FL}\n            android:dial="@drawable/dial_blank" android:hand_hour="@drawable/hand_hour" android:hand_minute="@drawable/hand_minute" />',
       '    </FrameLayout>']
kt_clocks = []
for name, res, n in fonts:
    key = name.lower()
    ids = []
    for i in range(n):
        vid = f"tc_{key}_{i}"
        out.append(f'    <FrameLayout android:id="@+id/{vid}_w" {FL} android:visibility="gone">')
        out.append(f'        <TextClock android:id="@+id/{vid}" {FL}\n            android:fontFamily="@font/{res}" android:includeFontPadding="false" android:maxLines="1" android:textAllCaps="true"\n            android:gravity="center" android:textColor="#FFFFFFFF" android:textSize="20sp" />')
        out.append('    </FrameLayout>')
        ids.append(f"R.id.{vid}_w to R.id.{vid}")
    kt_clocks.append(f"        LiveFont.{name} to listOf({', '.join(ids)}),")
chrono_fonts = ["clk_label", "clk_label", "clk_manrope", "clk_manrope", "clk_ar_cairo", "clk_ar_cairo"]
for i, f in enumerate(chrono_fonts):
    out.append(f'    <FrameLayout android:id="@+id/ch_{i}_w" {FL} android:visibility="gone">')
    out.append(f'        <Chronometer android:id="@+id/ch_{i}" {FL}\n            android:fontFamily="@font/{f}" android:includeFontPadding="false" android:maxLines="1"\n            android:gravity="center" android:textColor="#FFFFFFFF" android:textSize="14sp" />')
    out.append('    </FrameLayout>')
out.append(f'    <ImageView android:id="@+id/fx" {FL}\n        android:scaleType="fitXY" android:contentDescription="@null" android:visibility="gone" />')
HITS = 24
for i in range(HITS):
    out.append(f'    <FrameLayout android:id="@+id/hit_{i}_w" {FL} android:visibility="gone">')
    out.append(f'        <ImageView android:id="@+id/hit_{i}" {FL} android:contentDescription="@null" />')
    out.append('    </FrameLayout>')
out.append('</FrameLayout>')
open("app/src/main/res/layout/widget_root.xml", "w").write("\n".join(out) + "\n")

kt = f'''package com.smrh.zujaj.widget

import com.smrh.zujaj.R
import com.smrh.zujaj.render.LiveFont

/** Generated by tools/gen_widget_layout.py: view ids of the live slots in widget_root.xml */
object Slots {{
    val clocks: Map<LiveFont, List<Pair<Int, Int>>> = mapOf(
{chr(10).join(kt_clocks)}
    )
    val chronos: List<Pair<Int, Int>> = listOf({', '.join(f"R.id.ch_{i}_w to R.id.ch_{i}" for i in range(len(chrono_fonts)))})
    val hits: List<Pair<Int, Int>> = listOf({', '.join(f"R.id.hit_{i}_w to R.id.hit_{i}" for i in range(HITS))})
}}
'''
open("app/src/main/java/com/smrh/zujaj/widget/Slots.kt", "w").write(kt)
print(len(fonts), "fonts", sum(f[2] for f in fonts), "clock slots")
